"""Package directly generated carousel pages at exactly 2160x2700.

Artwork is generated by the built-in image tool. This script preserves its
aspect ratio, exports the five final PNGs, and builds an image-based PDF.
"""
import base64
from pathlib import Path
import shutil
import subprocess
import tempfile
import zipfile

from PIL import Image
from pypdf import PdfReader

HERE = Path(__file__).resolve().parent
OUT = HERE.parent
W, H = 1080, 1350
URL = 'https://github.com/deepseek-ai/dsh-superagent-prototype'


def render(browser, args, src, scale=1):
    temp_root = Path(tempfile.gettempdir()).resolve()
    profile = Path(tempfile.mkdtemp(prefix='li016-render-')).resolve()
    if not profile.is_relative_to(temp_root):
        raise RuntimeError('Unexpected temporary profile path')
    try:
        command = [str(browser), '--headless', '--disable-gpu', '--hide-scrollbars',
                   '--no-first-run', '--no-default-browser-check', '--disable-extensions',
                   '--disable-background-networking', f'--force-device-scale-factor={scale}',
                   '--window-size=1080,1350', '--virtual-time-budget=1200',
                   f'--user-data-dir={profile}', *args, src.as_uri()]
        result = subprocess.run(command, capture_output=True, timeout=60,
                                creationflags=subprocess.CREATE_NO_WINDOW)
        if result.returncode:
            raise RuntimeError(result.stderr.decode(errors='replace')[-1500:])
    finally:
        if profile.is_relative_to(temp_root) and profile.name.startswith('li016-render-'):
            shutil.rmtree(profile)


def main():
    browser = next((p for p in (
        Path('C:/Program Files/Google/Chrome/Application/chrome.exe'),
        Path('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe')) if p.is_file()), None)
    if browser is None:
        raise RuntimeError('Local Chrome or Edge is required')
    slides = []
    for i in range(1, 6):
        native = HERE / f'direct-slide-{i:02d}.png'
        with Image.open(native) as im:
            if abs(im.width / im.height - .8) > .008:
                raise RuntimeError(f'Unexpected native aspect ratio on page {i}: {im.size}')
            print(f'Native page {i}: {im.width}x{im.height}', flush=True)
        data = base64.b64encode(native.read_bytes()).decode()
        svg = '<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1350" viewBox="0 0 1080 1350">'
        svg += '<rect width="1080" height="1350" fill="#FFFCF0"/>'
        svg += f'<image width="1080" height="1350" preserveAspectRatio="xMidYMid meet" href="data:image/png;base64,{data}"/>'
        if i == 5:
            svg += f'<a href="{URL}"><rect x="40" y="1215" width="1000" height="65" fill="white" fill-opacity="0.001"/></a>'
        svg += '</svg>'
        source = HERE / f'slide-{i:02d}.svg'
        source.write_text(svg, encoding='utf-8')
        slides.append(svg)
        png = OUT / f'slide-{i:02d}.png'
        render(browser, [f'--screenshot={png}'], source, 2)
        with Image.open(png) as im:
            if im.size != (2160, 2700):
                raise RuntimeError(f'Unexpected final dimensions: {png}')
        print(f'Exported page {i}/5: exact 2160x2700', flush=True)
    html = '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>DeepSeek Super-agent | madvibe.ai</title>'
    html += '<style>@page{size:1080px 1350px;margin:0}html,body{margin:0;padding:0}section{width:1080px;height:1350px;break-after:page;overflow:hidden}section:last-child{break-after:auto}svg{display:block;width:1080px;height:1350px}</style></head><body>'
    html += ''.join(f'<section aria-label="Page {i}">{svg}</section>' for i, svg in enumerate(slides, 1)) + '</body></html>'
    (HERE / 'index.html').write_text(html, encoding='utf-8')
    pdf = OUT / 'LI-016-deepseek-superagent.pdf'
    render(browser, [f'--print-to-pdf={pdf}', '--no-pdf-header-footer'], HERE / 'index.html')
    reader = PdfReader(pdf)
    assert len(reader.pages) == 5, 'Expected five PDF pages'
    assert all(abs(float(p.mediabox.width) / float(p.mediabox.height) - .8) < .001 for p in reader.pages)
    assert all(p['/Resources'].get('/XObject') for p in reader.pages), 'Missing raster artwork'
    assert reader.pages[4].get('/Annots'), 'Missing source link'
    overview = Image.new('RGB', (1816, 485), '#EAE7DB')
    for i in range(5):
        with Image.open(OUT / f'slide-{i+1:02d}.png') as im:
            overview.paste(im.convert('RGB').resize((348, 435), Image.Resampling.LANCZOS), (16+i*360, 25))
    overview.save(OUT / 'overview.png')
    with zipfile.ZipFile(OUT / 'LI-016-instagram-carousel.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        for i in range(1, 6):
            archive.write(OUT / f'slide-{i:02d}.png', arcname=f'slide-{i:02d}.png')
    print('Verified five image-based PDF pages, source link, and exact 4:5 PNGs.')


if __name__ == '__main__':
    main()
